"""Optional area-light rigs, owned by and parented to one studio object.

Only tagged direct children are managed. Existing scene lights are untouched.
Positions use studio-local coordinates, so moving/rotating the studio moves its rig.
Updating a preset resets managed lights to the parameter-defined arrangement.
"""

import bpy
from mathutils import Matrix, Vector

# -------------------------------------------------------------
# Global Mappings and Role Definitions
# -------------------------------------------------------------
LIGHT_COLOR_PROPERTIES = {
    'Key': 'key_light_color',
    'Fill': 'fill_light_color',
    'Rim': 'rim_light_color',
    'Top': 'top_light_color',
    'Front Fill': 'front_fill_light_color',
}

PRESET_LIGHT_ROLES = {
    'NONE': (),
    'SOFTBOX': ('Key', 'Fill'),
    'THREE_POINT': ('Key', 'Fill', 'Rim'),
    'OVERHEAD': ('Top', 'Front Fill'),
}

LIGHT_POWER_PROPERTIES = {
    role: prop_name.replace('_color', '_power')
    for role, prop_name in LIGHT_COLOR_PROPERTIES.items()
}

LIGHT_ENABLED_PROPERTIES = {
    role: prop_name.replace('_color', '_enabled')
    for role, prop_name in LIGHT_COLOR_PROPERTIES.items()
}

TARGET_TAG = 'studio_generator_target'
TRACK_NAME = 'Studio Aim'
LIGHT_ROLE_KEY = 'studio_generator_light_role'

LIGHTING_PRESETS = [
    ('NONE', 'None', "Remove this studio's generated lighting"),
    ('SOFTBOX', 'Softbox Pair', 'Large key light with a softer fill'),
    ('THREE_POINT', 'Three Point', 'Key, fill and rear rim lights'),
    ('OVERHEAD', 'Overhead', 'Top softbox with a gentle front fill'),
]

RIM_POSITIONS = [
    ('BACK_LEFT', 'Back Left', 'Position rim light behind and to the left'),
    ('BACK_CENTER', 'Back Center', 'Position rim light directly behind the subject'),
    ('BACK_RIGHT', 'Back Right', 'Position rim light behind and to the right'),
]

RIM_POSITION_COORDINATES = {
    'BACK_LEFT': (-0.22, 0.27, 0.82),
    'BACK_CENTER': (0.0, 0.35, 0.82),
    'BACK_RIGHT': (0.22, 0.27, 0.82),
}


# -------------------------------------------------------------
# Object Management Helpers
# -------------------------------------------------------------
def managed_lights(studio_object):
    """Use ownership and custom property tag, never names, to identify generated lights."""
    return [
        child for child in studio_object.children
        if child.type == 'LIGHT' and LIGHT_ROLE_KEY in child
    ]


def delete_light(light_object):
    """Remove one owned object; unlink light data block if no other users remain."""
    light_data = light_object.data
    bpy.data.objects.remove(light_object, do_unlink=True)
    if light_data.users == 0:
        bpy.data.lights.remove(light_data)


def remove_legacy_targets(studio_object):
    """Remove tracking empties and Track To constraints generated by older add-on versions."""
    legacy_targets = [
        child for child in studio_object.children
        if child.type == 'EMPTY' and child.get(TARGET_TAG)
    ]

    for light_obj in managed_lights(studio_object):
        for constraint in list(light_obj.constraints):
            is_legacy_target = constraint.target in legacy_targets
            is_legacy_named = constraint.name == TRACK_NAME
            if constraint.type == 'TRACK_TO' and (is_legacy_target or is_legacy_named):
                light_obj.constraints.remove(constraint)

    for target_object in legacy_targets:
        bpy.data.objects.remove(target_object, do_unlink=True)


# -------------------------------------------------------------
# Main Lighting Logic
# -------------------------------------------------------------
def update_lighting(studio_object):
    """Create, configure, or clean up the light rig to match current settings."""
    settings = studio_object.studio_settings

    # Guard against recursive update loops
    if settings.initializing_light_power:
        return

    # 1. One-time legacy migration for individual light power properties
    if not settings.individual_power_initialized:
        settings.initializing_light_power = True
        try:
            default_ratios = {
                'Key': 1.0,
                'Fill': 0.45,
                'Rim': 0.75,
                'Top': 1.0,
                'Front Fill': 0.25,
            }
            for role, ratio in default_ratios.items():
                property_name = LIGHT_POWER_PROPERTIES[role]
                if not settings.is_property_set(property_name):
                    setattr(settings, property_name, settings.light_power * ratio)

            settings.individual_power_initialized = True
        finally:
            settings.initializing_light_power = False

    # 2. Clean up legacy tracking targets and gather existing managed lights
    remove_legacy_targets(studio_object)
    existing_lights = managed_lights(studio_object)

    if settings.lighting_preset == 'NONE':
        for light_obj in existing_lights:
            delete_light(light_obj)
        return

    # 3. Setup spatial dimensions and target aiming vector
    spread = settings.light_distance
    width = settings.width
    depth = settings.depth
    height = settings.height

    # Lights orient toward a studio-local focus point without needing dedicated empty objects
    aim_position = Vector((0.0, 0.0, min(1.0, height * 0.65)))

    # Lookup dynamic rim position coordinates based on user selection
    rim_coords = RIM_POSITION_COORDINATES.get(settings.rim_position, (0.22, 0.27, 0.82))

    # Preset templates: (role, (x_factor, y_factor, z_factor), power_ratio, size_ratio)
    key_preset = ('Key', (-0.28, -0.28, 0.78), 1.0, 1.0)
    fill_preset = ('Fill', (0.30, -0.18, 0.60), 0.45, 1.2)

    arrangements = {
        'SOFTBOX': [
            key_preset,
            fill_preset,
        ],
        'THREE_POINT': [
            key_preset,
            fill_preset,
            ('Rim', rim_coords, 0.75, 0.65),
        ],
        'OVERHEAD': [
            ('Top', (0.0, 0.0, 0.88), 1.0, 1.3),
            ('Front Fill', (0.0, -0.28, 0.50), 0.25, 0.8),
        ],
    }

    collection = studio_object.users_collection[0]
    retained_objects = set()

    # 4. Instantiate or re-use existing lights per required role
    for role, (norm_x, norm_y, norm_z), _, size_ratio in arrangements[settings.lighting_preset]:
        light_obj = next(
            (
                light for light in existing_lights
                if light.get(LIGHT_ROLE_KEY) == role and light not in retained_objects
            ),
            None,
        )

        if light_obj is None:
            light_data = bpy.data.lights.new(f'{studio_object.name} | {role}', 'AREA')
            light_obj = bpy.data.objects.new(light_data.name, light_data)
            collection.objects.link(light_obj)

            # Establish studio parent hierarchy in local space
            light_obj.parent = studio_object
            light_obj.matrix_parent_inverse = Matrix.Identity(4)
            light_obj[LIGHT_ROLE_KEY] = role

        # Ensure unique data block so edits don't bleed into duplicated studios
        if light_obj.data.users > 1:
            light_obj.data = light_obj.data.copy()

        retained_objects.add(light_obj)

        # 5. Position and orient toward center aim point
        light_obj.location = (
            width * norm_x * spread,
            depth * norm_y * spread,
            height * norm_z,
        )
        direction = aim_position - light_obj.location
        light_obj.rotation_mode = 'QUATERNION'
        light_obj.rotation_quaternion = direction.to_track_quat('-Z', 'Y')
        light_obj.scale = (1.0, 1.0, 1.0)

        # 6. Apply light properties, colors, and visibility
        light_obj.data.type = 'AREA'
        light_obj.data.shape = 'DISK'
        light_obj.data.energy = getattr(settings, LIGHT_POWER_PROPERTIES[role])
        light_obj.data.size = settings.light_size * size_ratio

        light_enabled = getattr(settings, LIGHT_ENABLED_PROPERTIES[role])
        light_obj.hide_viewport = not light_enabled
        light_obj.hide_render = not light_enabled

        # Multiply individual light tint with overall master studio tint
        individual_color = getattr(settings, LIGHT_COLOR_PROPERTIES[role])
        light_obj.data.color = tuple(
            channel * tint
            for channel, tint in zip(individual_color, settings.light_color)
        )

    # 7. Prune lights no longer utilized by the active preset
    for light_obj in existing_lights:
        if light_obj not in retained_objects:
            delete_light(light_obj)


def reset_lighting_defaults(studio_object):
    """Restore all lighting RNA properties to factory defaults and rebuild the rig."""
    settings = studio_object.studio_settings

    property_names = [
        'light_power',
        'light_size',
        'light_distance',
        'light_color',
        'rim_position',
    ]
    property_names.extend(LIGHT_COLOR_PROPERTIES.values())
    property_names.extend(LIGHT_POWER_PROPERTIES.values())
    property_names.extend(LIGHT_ENABLED_PROPERTIES.values())
    property_names.extend([
        prop_name.replace('_color', '_expanded')
        for prop_name in LIGHT_COLOR_PROPERTIES.values()
    ])

    settings.initializing_light_power = True
    try:
        for prop_name in property_names:
            prop_def = settings.bl_rna.properties[prop_name]
            default_value = (
                tuple(prop_def.default_array)
                if prop_def.is_array
                else prop_def.default
            )
            setattr(settings, prop_name, default_value)

        settings.individual_power_initialized = True
    finally:
        settings.initializing_light_power = False

    update_lighting(studio_object)